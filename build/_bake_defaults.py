#!/usr/bin/env python3
"""
Write app/_bundled_defaults.py from LUMORA_BUNDLED_* env vars.

Called by both build-deb.sh and build-exe.bat right before PyInstaller, so
the produced binary ships with the right Supabase URL + anon key (and
optionally a pre-filled DB password / Gemini key) baked in.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "app" / "_bundled_defaults.py"


def _val(name: str, default: str = "") -> str:
    return (os.environ.get(name, default) or "").strip()


DEFAULT_DATABASE_URL = (
    "postgresql+asyncpg://postgres.ailespxrkdfvureeleox:OzP7sCzv1XRGjZnn"
    "@aws-1-ap-northeast-1.pooler.supabase.com:5432/postgres"
)


def main() -> int:
    bundled = {
        "supabase_url": _val(
            "LUMORA_BUNDLED_SUPABASE_URL", "https://ailespxrkdfvureeleox.supabase.co"
        ),
        "supabase_anon_key": _val(
            "LUMORA_BUNDLED_SUPABASE_KEY",
            "sb_publishable_n5-DKZgPSLAoDN53NsdFdw_GLPLbhMF",
        ),
        # Full Postgres connection URL — what the SQLAlchemy engine actually
        # uses. Default to the IPv4 pooler so the bundled artifact works on
        # any network, including IPv4-only home Wi-Fi.
        "database_url": _val("LUMORA_BUNDLED_DATABASE_URL", DEFAULT_DATABASE_URL),
    }
    pw = _val("LUMORA_BUNDLED_DB_PASSWORD")
    if pw:
        bundled["supabase_db_password"] = pw
    gk = _val("LUMORA_BUNDLED_GOOGLE_API_KEY")
    if gk:
        bundled["google_api_key"] = gk
    for extra in ("sender_name", "sender_company", "sender_website", "sender_email"):
        v = _val(f"LUMORA_BUNDLED_{extra.upper()}")
        if v:
            bundled[extra] = v

    OUT.write_text(
        '"""Auto-generated by build/_bake_defaults.py — do not edit by hand."""\n'
        "\n"
        "BUNDLED = " + json.dumps(bundled, indent=4) + "\n"
    )
    redacted = {}
    for k, v in bundled.items():
        if k in {"supabase_db_password", "google_api_key"}:
            redacted[k] = "***"
        elif k == "database_url" and v:
            # Hide the password in the URL but keep the host visible so we
            # can confirm the right project was baked in.
            try:
                from urllib.parse import urlsplit

                p = urlsplit(v)
                if p.username and p.password:
                    redacted[k] = (
                        f"postgresql+asyncpg://{p.username}:***@{p.hostname}"
                        f":{p.port}/{p.path.lstrip('/')}"
                    )
                else:
                    redacted[k] = v
            except Exception:
                redacted[k] = "***"
        else:
            redacted[k] = v
    print(f"  baked {OUT} ← {redacted}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
